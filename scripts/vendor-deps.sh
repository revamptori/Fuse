#!/usr/bin/env bash
# Fetch the exact dependency sources needed by the engine from upstream Git tags
# into rust/vendor/ and point cargo at them. This exists for offline/air-gapped
# development; normal builds use crates.io.
#
# Usage: scripts/vendor-deps.sh [dest]   (default: rust/vendor)
set -euo pipefail
DEST="${1:-$(cd "$(dirname "$0")/.." && pwd)/rust/vendor}"
WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT
mkdir -p "$DEST"
fetch() { # repo tag dirname [subdir]
  local repo="$1" tag="$2" dir="$3" sub="${4:-}"
  echo "  $dir"
  curl -fsSL --retry 3 -o "$WORK/$dir.tar.gz" "https://codeload.github.com/$repo/tar.gz/refs/tags/$tag" \
    || curl -fsSL --retry 3 -o "$WORK/$dir.tar.gz" "https://codeload.github.com/$repo/tar.gz/refs/heads/$tag"
  local ex="$WORK/$dir-x"; mkdir -p "$ex"
  tar xzf "$WORK/$dir.tar.gz" -C "$ex"
  local root; root=$(find "$ex" -maxdepth 1 -mindepth 1 -type d | head -1)
  rm -rf "${DEST:?}/$dir"
  cp -r "$root/${sub}" "$DEST/$dir"
}
echo "Vendoring engine dependencies into $DEST"
fetch Frommi/miniz_oxide 0.8.9 miniz_oxide miniz_oxide/
fetch jni-rs/jni-rs v0.21.1 jni
fetch jni-rs/jni-sys v0.3.1 jni-sys
fetch rust-lang/cfg-if 1.0.0 cfg-if
fetch emk/cesu8-rs master cesu8
fetch Marwes/combine v4.6.7 combine
fetch rust-lang/log 0.4.22 log
fetch dtolnay/thiserror 1.0.69 thiserror
fetch dtolnay/thiserror 1.0.69 thiserror-impl impl/
fetch dtolnay/proc-macro2 1.0.89 proc-macro2
fetch dtolnay/quote 1.0.37 quote
fetch dtolnay/syn 2.0.87 syn
fetch dtolnay/unicode-ident 1.0.13 unicode-ident
fetch BurntSushi/walkdir 2.5.0 walkdir
fetch BurntSushi/same-file 1.0.6 same-file
fetch BurntSushi/memchr 2.7.4 memchr
fetch tokio-rs/bytes 1.7.2 bytes
# Normalise workspace sections that break isolated vendored crates.
python3 - "$DEST" <<'PY'
import glob, re, sys, os
dest = sys.argv[1]
for f in glob.glob(os.path.join(dest, '*', 'Cargo.toml')):
    s = open(f).read()
    if re.search(r'^\[workspace', s, re.M):
        s = re.sub(r'\n\[workspace(\.[^\]]*)?\].*?(?=\n\[|\Z)', '\n', s, flags=re.S)
        open(f, 'w').write(s)
for f in glob.glob(os.path.join(dest, '*', 'Cargo.toml')):
    s = open(f).read()
    if 'name = "thiserror"' in s:
        s = s.replace('path = "impl"', 'path = "../thiserror-impl"')
        open(f, 'w').write(s)
PY
cat > "$(dirname "$DEST")/.cargo/config-vendor.toml" <<CFG
# Generated by scripts/vendor-deps.sh -- remove to return to crates.io.
[source.crates-io]
replace-with = "vendored-sources"

[source.vendored-sources]
directory = "vendor"
CFG
echo "done. Enable with: cp rust/.cargo/config-vendor.toml rust/.cargo/config.toml"
